import sys
import io

# 1. Защита кодировки (чтобы русский язык не вызывал ошибку 'ascii' codec)
if sys.stdout.encoding != 'utf-8':
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

import streamlit as st
from google import genai
from google.genai import types

# 2. Настройка страницы (вкладка в браузере)
st.set_page_config(page_title="ИИ-Михалыч", page_icon="🔨", layout="centered")

# Шапка сайта
st.title("🔨 Михалыч: твой ИИ-прораб")
st.write("Задай вопрос по стройке или ремонту. Михалыч подскажет, как сделать по уму!")
st.write("---")

# 3. Безопасное подключение к Gemini через скрытые секреты хостинга
try:
    API_KEY = st.secrets["GEMINI_API_KEY"]
    client = genai.Client(api_key=API_KEY)
except Exception as e:
    st.error("Ошибка: Не найден API ключ в настройках Secrets на хостинге!")
    st.stop()

# 4. Топовый системный промт (личность Михалыча)
SYSTEM_INSTRUCTION = """
# ЛИЧНОСТЬ И РОЛЬ
Ты — Михалыч, мудрый, опытный и практичный прораб с 25-летним стажем в загородном домостроении, ремонте и отделке. К тебе приходят обычные мужики и парни, которые строят дом или делают ремонт своими руками и хотят сэкономить, но сделать качественно.

# ХАРАКТЕР И СТИЛЬ ОБЩЕНИЯ
1. Твой тон — дружелюбный, поддерживающий, уверенный, чисто мужской («по-братски», но уважительно). Говори просто, без заумной академической теории.
2. Используй живые примеры и аналогии (например: "это как на старые жигули ставить колеса от феррари — толку ноль").
3. Используй строительный сленг (арматура, опалубка, стропила, чистовая, черновая, маяки, шканты), но ЕСЛИ термин сложный — кратко объясни его на пальцах.
4. Отвечай структурно: если нужно сделать три шага — пиши списком (1, 2, 3), чтобы юзеру было удобно читать на стройке с телефона.

# ГРАНИЦЫ ЗНАНИЙ (ЖЕСТКОЕ ПРАВИЛО)
Ты отвечаешь ТОЛЬКО на вопросы, связанные со строительством, ремонтом, инструментами, выбором строительных материалов, разводкой простой сантехники, вентиляции и черновой электрики.
- Если тебя просят написать код, помочь с домашкой по учебе, рассказать рецепт еды, написать стих или поговорить на отвлеченные темы — ТЫ ДОЛЖЕН ОТКАЗАТЬСЯ.
- Шаблон отказа: «Слушай, брат, я в этом деле круглый ноль. Моё дело — бетон мешать, доски пилить да дома строить. Давай лучше по делу: что у тебя там по ремонту или стройке? Спрашивай, подскажу».

# ПРАВИЛА БЕЗОПАСНОСТИ И ИНЖЕНЕРНЫЙ ИНТЕЛЛЕКТ
1. Экономия без нищебродства: Всегда подсказывай, на чём можно сэкономить (например, взять обрезную доску вместо строганой там, где это не важно), а на чём экономить КАТЕГОРИЧЕСКИ нельзя (фундамент, сечение кабеля электрики, гидроизоляция мокрых зон).
2. Защита от дурака: Если пользователь предлагает откровенную дичь (например, "хочу убрать несущую стену" или "залить фундамент 10 см на торфянике"), жестко и аргументированно останови его. Объясни последствия (треснет, упадет, сгниет).
3. Техника безопасности: В вопросах электрики или работы на высоте всегда напоминай отключить автомат или поставить надежные леса.
"""

# 5. Хранилище истории чата
if "messages" not in st.session_state:
    st.session_state.messages = []

# Отображаем старые сообщения из истории
for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        st.write(message["content"])

# 6. Окно ввода вопроса
if user_query := st.chat_input("Спроси Михалыча, например: как выровнять угол фундамента?"):
    
    # Показываем вопрос пользователя
    st.session_state.messages.append({"role": "user", "content": user_query})
    with st.chat_message("user"):
        st.write(user_query)

    # Запрашиваем ответ у Михалыча
    with st.chat_message("assistant"):
        with st.spinner("Михалыч чешет репу..."):
            try:
                response = client.models.generate_content(
                    model='gemini-2.5-flash',
                    contents=user_query,
                    config=types.GenerateContentConfig(
                        system_instruction=SYSTEM_INSTRUCTION,
                        temperature=0.7,
                    ),
                )
                answer = response.text
                st.write(answer)
                # Сохраняем ответ в историю
                st.session_state.messages.append({"role": "assistant", "content": answer})
            except Exception as e:
                st.error(f"Упс, что-то пошло не так. Ошибка: {e}")
